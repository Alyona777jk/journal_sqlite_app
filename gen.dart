import 'dart:io';

void main() {
  final file = File('lib/database/database_helper.dart');
  
  final buffer = StringBuffer();
  buffer.writeln("import 'package:flutter/foundation.dart';");
  buffer.writeln("import 'package:sqflite/sqflite.dart';");
  buffer.writeln("import 'package:sqflite_common_ffi_web/sqflite_ffi_web.dart';");
  buffer.writeln("import 'package:path/path.dart';");
  buffer.writeln("import 'package:flutter/material.dart';");
  buffer.writeln("import '../models/journal_entry.dart';");
  buffer.writeln("import '../models/tag.dart';");
  buffer.writeln("");
  buffer.writeln("class DatabaseHelper {");
  buffer.writeln("  static final DatabaseHelper instance = DatabaseHelper._init();");
  buffer.writeln("  static Database? _database;");
  buffer.writeln("");
  buffer.writeln("  DatabaseHelper._init();");
  buffer.writeln("");
  buffer.writeln("  Future<Database> get database async {");
  buffer.writeln("    if (_database != null) return _database!;");
  buffer.writeln("    _database = await _initDB('journal.db');");
  buffer.writeln("    return _database!;");
  buffer.writeln("  }");
  buffer.writeln("");
  buffer.writeln("  Future<Database> _initDB(String filePath) async {");
  buffer.writeln("    if (kIsWeb) {");
  buffer.writeln("      databaseFactory = databaseFactoryFfiWeb;");
  buffer.writeln("    }");
  buffer.writeln("    final dbPath = await getDatabasesPath();");
  buffer.writeln("    final path = join(dbPath, filePath);");
  buffer.writeln("    return await openDatabase(");
  buffer.writeln("      path,");
  buffer.writeln("      version: 1,");
  buffer.writeln("      onCreate: _onCreate,");
  buffer.writeln("    );");
  buffer.writeln("  }");
  buffer.writeln("");
  buffer.writeln("  Future<void> _onCreate(Database db, int version) async {");
  buffer.writeln("    await db.execute('''");
  buffer.writeln("      CREATE TABLE journal_entries (");
  buffer.writeln("        id INTEGER PRIMARY KEY AUTOINCREMENT,");
  buffer.writeln("        title TEXT NOT NULL,");
  buffer.writeln("        content TEXT NOT NULL,");
  buffer.writeln("        mood TEXT NOT NULL,");
  buffer.writeln("        created_at TEXT NOT NULL,");
  buffer.writeln("        updated_at TEXT NOT NULL,");
  buffer.writeln("        is_favorite INTEGER NOT NULL DEFAULT 0,");
  buffer.writeln("        word_count INTEGER NOT NULL DEFAULT 0");
  buffer.writeln("      )");
  buffer.writeln("    ''');");
  buffer.writeln("");
  buffer.writeln("    await db.execute('''");
  buffer.writeln("      CREATE TABLE tags (");
  buffer.writeln("        id INTEGER PRIMARY KEY AUTOINCREMENT,");
  buffer.writeln("        name TEXT NOT NULL UNIQUE,");
  buffer.writeln("        color TEXT NOT NULL,");
  buffer.writeln("        created_at TEXT NOT NULL");
  buffer.writeln("      )");
  buffer.writeln("    ''');");
  buffer.writeln("");
  buffer.writeln("    await db.execute('''");
  buffer.writeln("      CREATE TABLE entry_tags (");
  buffer.writeln("        entry_id INTEGER NOT NULL,");
  buffer.writeln("        tag_id INTEGER NOT NULL,");
  buffer.writeln("        PRIMARY KEY (entry_id, tag_id),");
  buffer.writeln("        FOREIGN KEY (entry_id) REFERENCES journal_entries (id) ON DELETE CASCADE,");
  buffer.writeln("        FOREIGN KEY (tag_id) REFERENCES tags (id) ON DELETE CASCADE");
  buffer.writeln("      )");
  buffer.writeln("    ''');");
  buffer.writeln("");
  buffer.writeln("    await db.execute('CREATE INDEX idx_entries_created_at ON journal_entries(created_at)');");
  buffer.writeln("    await db.execute('CREATE INDEX idx_entries_mood ON journal_entries(mood)');");
  buffer.writeln("    await db.execute('CREATE INDEX idx_tags_name ON tags(name)');");
  buffer.writeln("  }");
  buffer.writeln("");
  buffer.writeln("  Future<int> insertEntry(JournalEntry entry, List<int> tagIds) async {");
  buffer.writeln("    final db = await instance.database;");
  buffer.writeln("    return await db.transaction((txn) async {");
  buffer.writeln("      final entryId = await txn.insert('journal_entries', entry.toMap());");
  buffer.writeln("      for (var tagId in tagIds) {");
  buffer.writeln("        await txn.insert('entry_tags', {");
  buffer.writeln("          'entry_id': entryId,");
  buffer.writeln("          'tag_id': tagId,");
  buffer.writeln("        });");
  buffer.writeln("      }");
  buffer.writeln("      return entryId;");
  buffer.writeln("    });");
  buffer.writeln("  }");
  buffer.writeln("");
  buffer.writeln("  Future<int> updateEntry(JournalEntry entry, List<int> tagIds) async {");
  buffer.writeln("    final db = await instance.database;");
  buffer.writeln("    return await db.transaction((txn) async {");
  buffer.writeln("      final rows = await txn.update(");
  buffer.writeln("        'journal_entries',");
  buffer.writeln("        entry.toMap(),");
  buffer.writeln("        where: 'id = ?',");
  buffer.writeln("        whereArgs: [entry.id],");
  buffer.writeln("      );");
  buffer.writeln("      await txn.delete('entry_tags', where: 'entry_id = ?', whereArgs: [entry.id]);");
  buffer.writeln("      for (var tagId in tagIds) {");
  buffer.writeln("        await txn.insert('entry_tags', {");
  buffer.writeln("          'entry_id': entry.id,");
  buffer.writeln("          'tag_id': tagId,");
  buffer.writeln("        });");
  buffer.writeln("      }");
  buffer.writeln("      return rows;");
  buffer.writeln("    });");
  buffer.writeln("  }");
  buffer.writeln("");
  buffer.writeln("  Future<int> deleteEntry(int id) async {");
  buffer.writeln("    final db = await instance.database;");
  buffer.writeln("    return await db.transaction((txn) async {");
  buffer.writeln("      await txn.delete('entry_tags', where: 'entry_id = ?', whereArgs: [id]);");
  buffer.writeln("      return await txn.delete('journal_entries', where: 'id = ?', whereArgs: [id]);");
  buffer.writeln("    });");
  buffer.writeln("  }");
  buffer.writeln("");
  buffer.writeln("  Future<List<JournalEntry>> getEntries({String? searchQuery, String? moodFilter, int? tagIdFilter}) async {");
  buffer.writeln("    final db = await instance.database;");
  buffer.writeln("    String whereClause = '';");
  buffer.writeln("    List<dynamic> whereArgs = [];");
  buffer.writeln("    if (searchQuery != null && searchQuery.isNotEmpty) {");
  buffer.writeln("      whereClause += '(e.title LIKE ? OR e.content LIKE ?)';");
  buffer.writeln("      whereArgs.addAll(['%\$searchQuery%', '%\$searchQuery%']);");
  buffer.writeln("    }");
  buffer.writeln("    if (moodFilter != null && moodFilter.isNotEmpty) {");
  buffer.writeln("      if (whereClause.isNotEmpty) whereClause += ' AND ';");
  buffer.writeln("      whereClause += 'e.mood = ?';");
  buffer.writeln("      whereArgs.add(moodFilter);");
  buffer.writeln("    }");
  buffer.writeln("    if (tagIdFilter != null) {");
  buffer.writeln("      if (whereClause.isNotEmpty) whereClause += ' AND ';");
  buffer.writeln("      whereClause += 'e.id IN (SELECT entry_id FROM entry_tags WHERE tag_id = ?)';");
  buffer.writeln("      whereArgs.add(tagIdFilter);");
  buffer.writeln("    }");
  buffer.writeln("    final query = '''");
  buffer.writeln("      SELECT ");
  buffer.writeln("        e.*, ");
  buffer.writeln("        t.id AS tag_id, ");
  buffer.writeln("        t.name AS tag_name, ");
  buffer.writeln("        t.color AS tag_color, ");
  buffer.writeln("        t.created_at AS tag_created_at");
  buffer.writeln("      FROM journal_entries e");
  buffer.writeln("      LEFT JOIN entry_tags et ON e.id = et.entry_id");
  buffer.writeln("      LEFT JOIN tags t ON et.tag_id = t.id");
  buffer.writeln("      \${whereClause.isNotEmpty ? 'WHERE ' + whereClause : ''}");
  buffer.writeln("      ORDER BY e.created_at DESC");
  buffer.writeln("    ''';");
  buffer.writeln("    final result = await db.rawQuery(query, whereArgs);");
  buffer.writeln("    Map<int, JournalEntry> entriesMap = {};");
  buffer.writeln("    for (var row in result) {");
  buffer.writeln("      int entryId = row['id'] as int;");
  buffer.writeln("      if (!entriesMap.containsKey(entryId)) {");
  buffer.writeln("        entriesMap[entryId] = JournalEntry.fromMap(row, tags: []);");
  buffer.writeln("      }");
  buffer.writeln("      if (row['tag_id'] != null) {");
  buffer.writeln("        final tag = Tag(");
  buffer.writeln("          id: row['tag_id'] as int,");
  buffer.writeln("          name: row['tag_name'] as String,");
  buffer.writeln("          color: Color(int.parse((row['tag_color'] as String).replaceAll('#', 'FF'), radix: 16)),");
  buffer.writeln("          createdAt: row['tag_created_at'] as String,");
  buffer.writeln("        );");
  buffer.writeln("        entriesMap[entryId]!.tags.add(tag);");
  buffer.writeln("      }");
  buffer.writeln("    }");
  buffer.writeln("    return entriesMap.values.toList();");
  buffer.writeln("  }");
  buffer.writeln("");
  buffer.writeln("  Future<int> insertTag(Tag tag) async {");
  buffer.writeln("    final db = await instance.database;");
  buffer.writeln("    return await db.insert('tags', tag.toMap());");
  buffer.writeln("  }");
  buffer.writeln("");
  buffer.writeln("  Future<List<Tag>> getTagsWithUsage() async {");
  buffer.writeln("    final db = await instance.database;");
  buffer.writeln("    final result = await db.rawQuery('''");
  buffer.writeln("      SELECT t.*, COUNT(et.entry_id) as usage_count");
  buffer.writeln("      FROM tags t");
  buffer.writeln("      LEFT JOIN entry_tags et ON t.id = et.tag_id");
  buffer.writeln("      GROUP BY t.id");
  buffer.writeln("      ORDER BY t.name ASC");
  buffer.writeln("    ''');");
  buffer.writeln("    return result.map((json) => Tag.fromMap(json)).toList();");
  buffer.writeln("  }");
  buffer.writeln("");
  buffer.writeln("  Future<int> deleteTag(int id) async {");
  buffer.writeln("    final db = await instance.database;");
  buffer.writeln("    return await db.delete('tags', where: 'id = ?', whereArgs: [id]);");
  buffer.writeln("  }");
  buffer.writeln("");
  buffer.writeln("  Future> getMoodBreakdown() async {");
  buffer.writeln("    final db = await instance.database;");
  buffer.writeln("    final result = await db.rawQuery('''");
  buffer.writeln("      SELECT mood, COUNT(*) as count ");
  buffer.writeln("      FROM journal_entries ");
  buffer.writeln("      GROUP BY mood");
  buffer.writeln("    ''');");
  buffer.writeln("    Map<String, int> map = {};");
  buffer.writeln("    for (var row in result) {");
  buffer.writeln("      map[row['mood'] as String] = row['count'] as int;");
  buffer.writeln("    }");
  buffer.writeln("    return map;");
  buffer.writeln("  }");
  buffer.writeln("");
  buffer.writeln("  Future<int> getTotalEntriesCount() async {");
  buffer.writeln("    final db = await instance.database;");
  buffer.writeln("    final result = await db.rawQuery('SELECT COUNT(*) as count FROM journal_entries');");
  buffer.writeln("    return Sqflite.firstIntValue(result) ?? 0;");
  buffer.writeln("  }");
  buffer.writeln("}");

  file.writeAsStringSync(buffer.toString());
  print('Done writing database_helper.dart');
}
